"""
tools/document_generator.py — Multi-Format Document Generation with Artifact Linking.

Implements Capability 12:
- Generates PDF, DOCX, PPTX, XLSX, Markdown, and TXT documents.
- Automatically registers generated files with default_artifact_service.
- Adds PPTX presentation generation with title slide and content slides.
- Returns verified artifact metadata and download links.
"""

import os
import uuid
from typing import Dict, Any, List, Optional

from tools.doc_generator import generate_document as base_generate_document
from services.artifact_service import default_artifact_service


def generate_presentation_pptx(
    title: str,
    slides_data: List[Dict[str, Any]],
    output_path: str
) -> str:
    """Generates a PPTX presentation from structured slide data."""
    from pptx import Presentation
    from pptx.util import Inches, Pt

    prs = Presentation()

    # 1. Title slide
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    slide.shapes.title.text = title
    if len(slide.placeholders) > 1:
        slide.placeholders[1].text = "Generated by SPARK-AI"

    # 2. Content slides
    bullet_slide_layout = prs.slide_layouts[1]
    for s_data in slides_data:
        s = prs.slides.add_slide(bullet_slide_layout)
        s.shapes.title.text = s_data.get("title", "Slide")
        body = s.placeholders[1]
        tf = body.text_frame
        bullets = s_data.get("bullets", [])
        if bullets:
            tf.text = bullets[0]
            for b in bullets[1:]:
                p = tf.add_paragraph()
                p.text = str(b)
        elif "content" in s_data:
            tf.text = s_data["content"]

    prs.save(output_path)
    return output_path


def create_document(
    format_type: str,
    title: str,
    content: str,
    filename: Optional[str] = None,
    table_data: Optional[List[List[Any]]] = None,
    slides_data: Optional[List[Dict[str, Any]]] = None,
    user_id: str = "default_user",
    session_id: Optional[str] = None
) -> Dict[str, Any]:
    """
    Generates a document of the requested format and registers it as an artifact.
    Supported formats: pdf, docx, pptx, xlsx, csv, md, txt.
    """
    fmt = format_type.lower().strip()

    if fmt == "pptx":
        # Handle PPTX directly
        outputs_dir = os.path.join(os.getcwd(), "outputs")
        os.makedirs(outputs_dir, exist_ok=True)
        fname = filename or f"{title.replace(' ', '_').lower()[:30]}_{uuid.uuid4().hex[:6]}.pptx"
        fpath = os.path.join(outputs_dir, fname)

        slides = slides_data or [{"title": "Overview", "bullets": [line.strip("- ") for line in content.split("\n") if line.strip()]}]
        generate_presentation_pptx(title, slides, fpath)

        with open(fpath, "rb") as f:
            art = default_artifact_service.save_artifact(
                file_name=fname,
                content=f.read(),
                user_id=user_id,
                session_id=session_id,
                mime_type="application/vnd.openxmlformats-officedocument.presentationml.presentation"
            )
        return {
            "success": True,
            "filename": fname,
            "format": "pptx",
            "file_path": fpath,
            "artifact": art.to_dict()
        }

    # Delegate to base_generate_document for PDF, DOCX, XLSX, CSV, MD, TXT
    res = base_generate_document(
        format_type=fmt,
        title=title,
        content=content,
        filename=filename,
        table_data=table_data,
        user_id=user_id
    )

    if res.get("success") and "file_path" in res:
        fpath = res["file_path"]
        fname = res.get("filename", os.path.basename(fpath))
        with open(fpath, "rb") as f:
            art = default_artifact_service.save_artifact(
                file_name=fname,
                content=f.read(),
                user_id=user_id,
                session_id=session_id
            )
        res["artifact"] = art.to_dict()

    return res
